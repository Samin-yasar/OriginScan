/**
 * Retrieves bundled country details by name or alias.
 * @param {string} countryName
 * @returns {{ population: number, capital: string, latlng: [number, number], currencies: string } | null}
 */
export function getBundledCountryDetails(countryName) {
  if (!countryName) return null;
  const direct = COUNTRY_DATA[countryName];
  if (direct) return direct;

  // Case-insensitive / whitespace fallback
  const norm = countryName.toLowerCase().trim();
  for (const key of Object.keys(COUNTRY_DATA)) {
    if (key.toLowerCase() === norm) {
      return COUNTRY_DATA[key];
    }
  }
  return null;
}
